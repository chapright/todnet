// The shipped locales. The key is the BCP 47 tag, so it can be handed
// straight to the browser.
export const LOCALES = {
  en: { name: 'English', dir: 'ltr', strings: en },
  fa: { name: 'فارسی', dir: 'rtl', strings: fa },
};

export const DEFAULT_LOCALE = 'en';

let active = DEFAULT_LOCALE;

// setLocale switches the active table. It reports whether anything changed,
// so the caller knows whether the interface has to be rebuilt.
export function setLocale(code) {
  const next = Object.prototype.hasOwnProperty.call(LOCALES, code) ? code : DEFAULT_LOCALE;
  const changed = next !== active;
  active = next;
  return changed;
}

export function getLocale() { return active; }

// locale returns the active locale's metadata.
export function locale() { return LOCALES[active]; }

// isRTL reports whether the active language is written right to left.
export function isRTL() { return LOCALES[active].dir === 'rtl'; }

export function t(key, vars) {
  const table = LOCALES[active].strings;
  let s = table[key];
  if (s == null) {
    // Missing keys should be loud in development and harmless in production.
    if (typeof console !== 'undefined') console.warn('[i18n] missing key:', key);
    return key;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  }
  return s;
}

export function has(key) {
  return Object.prototype.hasOwnProperty.call(LOCALES[active].strings, key);
}

export function strings() { return LOCALES[active].strings; }
